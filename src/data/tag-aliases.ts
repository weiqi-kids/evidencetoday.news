/** 把一個標籤收斂成正規名。表裡沒有的原樣回傳。 */
export function canonicalTag(tag: string): string {
  return TAG_ALIASES[tag.trim()] ?? tag.trim();
}

/** 收斂一組標籤並去重，保留原順序。 */
export function canonicalTags(tags: readonly string[] = []): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const t of tags) {
    const c = canonicalTag(t);
    if (!c || seen.has(c)) continue;
    seen.add(c);
    out.push(c);
  }
  return out;
}
